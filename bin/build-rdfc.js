#!/usr/bin/env node
/*
 * rdf-array: writes rdf/rdf-canon, tests of RDFC-1.0 over sequences (rdf-array's docs/rdfc-array.md).
 * Each case is canonicalized by rdf-canonize-array under shuffled blank node labels and quad orders,
 * which must all agree; oxigraph-array's testsuite then checks the result independently.
 * `node bin/build-rdfc.js --check` rebuilds and fails if anything would change.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'rdf', 'rdf-canon');
const {canonize, NQuads} = require(
  process.env.RDF_CANONIZE_ARRAY || path.join(ROOT, '..', 'rdf-canonize-array'));
const CHECK = process.argv.includes('--check');
const P = '<http://example.org/p>';
const Q = '<http://example.org/q>';
const S = '<http://example.org/s>';
const G = '<http://example.org/g>';

const CASES = [
  ['ground', 'a sequence without blank nodes is written as it is', [
    `${S} ${P} ("a" 1 <http://example.org/o>) .`.replace(' 1 ', ' "1"^^<http://www.w3.org/2001/XMLSchema#integer> ')]],
  ['empty', 'the empty sequence, and an empty one nested', [`${S} ${P} () .`, `${S} ${Q} (()) .`]],
  ['spelling', 'one space between elements, none inside the parentheses, and literal escapes', [
    `${S} ${P} (   "a\\tb"   ( "(" )   "c"@en   ) .`]],
  ['one-bnode', 'a blank node inside a sequence is relabelled', [`${S} ${P} (_:x) .`]],
  ['bnode-with-triples', 'a blank node inside a sequence has triples of its own', [
    `${S} ${P} (_:x "a") .`, `_:x ${Q} "b" .`]],
  ['positions', 'first degree tells apart two blank nodes by their positions', [`${S} ${P} (_:x _:y) .`]],
  ['repeated', 'one blank node twice in a sequence', [`${S} ${P} (_:x _:x _:y) .`]],
  ['nested', 'blank nodes in nested sequences', [`${S} ${P} (_:x (_:y (_:x)) _:z) .`, `_:z ${Q} _:y .`]],
  ['subject', 'a sequence as a subject', [`(_:x "a") ${P} _:y .`, `_:y ${Q} (_:x) .`]],
  ['graph', 'a blank node graph name beside a sequence', [`_:s ${P} (_:x) _:g .`, `_:x ${Q} "a" _:g .`]],
  ['named-graph', 'the same sequence in two graphs', [`${S} ${P} (_:x) ${G} .`, `${S} ${P} (_:x) .`]],
  ['same-sequence-two-subjects', 'tied subjects of equal sequences', [`_:a ${P} (_:x _:y) .`, `_:b ${P} (_:x _:y) .`]],
  ['symmetric', 'an automorphism swaps the two blank nodes', [`${S} ${P} (_:x _:y) , (_:y _:x) .`
    .replace(' , ', ` .\n${S} ${P} `)].join('\n').split('\n')],
  ['two-subjects-crossed', 'an automorphism swaps subjects and elements together', [
    `_:a ${P} (_:x _:y) .`, `_:b ${P} (_:y _:x) .`]],
  ['parity', 'every pair of blank nodes occurs once, so only the whole sequence tells this from its relabelling', [
    `${S} ${P} (_:x _:y _:a) .`, `${S} ${P} (_:x _:u _:b) .`, `${S} ${P} (_:w _:y _:b) .`, `${S} ${P} (_:w _:u _:a) .`]],
  ['latin-rectangle', 'every blank node once at every position: all tie at first degree, with no automorphism', [
    `${S} ${P} (_:a _:f _:c _:d _:e _:b) .`, `${S} ${P} (_:c _:e _:b _:a _:d _:f) .`,
    `${S} ${P} (_:d _:c _:a _:b _:f _:e) .`]],
  ['undef-ground', 'a slot is written undef, whatever its case in the input', [`${S} ${P} (UNDEF "a" (Undef)) .`]],
  ['undef-position', 'a slot counts as an element', [`${S} ${P} (undef _:x) .`, `${S} ${Q} (_:x undef) .`]],
  ['undef-shorter', 'a sequence with a slot differs from the shorter one', [`_:x ${P} (_:y undef) .`, `_:x ${P} (_:y) .`]],
  ['undef-symmetric', 'an automorphism swaps blank nodes around a slot', [
    `${S} ${P} (_:x undef _:y) .`, `${S} ${P} (_:y undef _:x) .`]],
  ['undef-only-difference', 'tied blank nodes told apart only by where a slot is', [
    `_:a ${P} (_:x undef) .`, `_:b ${P} (undef _:x) .`]]
];

let seed = 20261103;
const random = n => {
  seed = (seed * 1103515245 + 12345) & 0x7fffffff;
  return seed % n;
};
const shuffle = list => {
  const out = [...list];
  for(let i = out.length - 1; i > 0; i--) {
    const j = random(i + 1);
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
};
const options = {algorithm: 'RDFC-1.0', maxWorkFactor: Infinity};

async function canonical(name, lines) {
  const text = lines.join('\n') + '\n';
  const result = await canonize(NQuads.parse(text), options);
  const labels = [...new Set(text.match(/_:\w+/g) || [])];
  for(let i = 0; i < 40; i++) {
    const target = shuffle(labels.map((_, k) => `_:n${k}`));
    const map = new Map(labels.map((label, k) => [label, target[k]]));
    const relabelled = shuffle(lines).join('\n').replace(/_:\w+/g, l => map.get(l)) + '\n';
    const other = await canonize(NQuads.parse(relabelled), options);
    if(other !== result) {
      throw new Error(`${name} depends on labels:\n${result}--\n${other}`);
    }
  }
  return result;
}

(async () => {
  const files = new Map();
  for(const [name, , lines] of CASES) {
    files.set(`${name}-in.nq`, lines.join('\n') + '\n');
    files.set(`${name}-rdfc10.nq`, await canonical(name, lines));
  }
  files.set('manifest.ttl', `# Generated by bin/build-rdfc.js.
@prefix : <manifest#> .
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
@prefix mf:   <http://www.w3.org/2001/sw/DataAccess/tests/test-manifest#> .
@prefix rdfc: <https://w3c.github.io/rdf-canon/tests/vocab#> .
@prefix rdft: <http://www.w3.org/ns/rdftest#> .

<manifest> a mf:Manifest ;
  rdfs:label "rdf-array: RDFC-1.0 over sequences" ;
  mf:entries (
${CASES.map(([name]) => `    :${name}`).join('\n')}
  ) .

${CASES.map(([name, comment]) => `:${name} a rdfc:RDFC10EvalTest ;
  mf:name "${name}" ;
  rdfs:comment "${comment}" ;
  rdft:approval rdft:Proposed ;
  mf:action <${name}-in.nq> ;
  mf:result <${name}-rdfc10.nq> .
`).join('\n')}`);
  let changed = 0;
  for(const [file, text] of files) {
    const target = path.join(OUT, file);
    const old = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
    if(old !== text) {
      changed++;
      if(CHECK) {
        console.error(`would change: ${file}`);
      } else {
        fs.writeFileSync(target, text);
      }
    }
  }
  console.log(`${CASES.length} tests, ${changed} files ${CHECK ? 'would change' : 'written'}`);
  process.exit(CHECK && changed ? 1 : 0);
})().catch(error => {
  console.error(error.message);
  process.exit(1);
});
